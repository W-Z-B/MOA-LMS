TITLE = "How the GSA LMS uses your personal data"

BODY = """\
The Guyana School of Agriculture (GSA) runs this Learning Management System (LMS) for teaching and learning. \
This notice says what the LMS holds about you, why, who sees it, how long it is kept, and what you can \
ask for. \
It is a draft, to be confirmed by GSA before it is published.

Who is responsible: the Guyana School of Agriculture, under the Data Protection Act 2023. Questions go to \
the GSA Data Protection Officer through the Registry or Human Resources.

What the LMS holds about you
- Who you are: your name, your student or employee number, your email and your campus. These come from \
the Student Records system (students) or the Human Resources system (staff); the LMS does not collect them \
from you.
- Your courses: the course sites you belong to and your role in each (student, lecturer or teaching \
assistant).
- Your work: what you submit for assignments (the file or text), when you submitted it and whether it was \
late.
- Your marks: the mark and feedback for each piece of work. You see them once your lecturer releases them.
- Completions: the courses you have completed. For staff development courses this is sent to the Human \
Resources system for your training record.
- Notifications sent to you, and whether you have read them.
- Your account: your username, your roles, and, for staff with administrative roles, your authenticator.

What the LMS records about your activity, and nothing more
- Each time you sign in or out, and from which network address. Failed sign-in attempts, to stop someone \
guessing passwords.
- Each time you download a course file or a submission.
- Each submission, mark and change made to a course, with who made it and when.
The LMS does not record how long you spend on a page, which pages you read, or your location, and it uses \
no advertising or tracking cookies. The only cookies keep you signed in and protect forms.

Why: to run your courses, to mark your work and send your coursework marks to the Student Records system, \
and to keep the system secure. The legal basis is GSA's public task of education and training.

Who sees it
- Your lecturers and teaching assistants see the work, marks and membership of the courses they teach.
- Course administrators and system administrators see what they need to run the courses.
- The auditor and the Data Protection Officer see records when they check how the system is used.
- Other students never see your work or your marks.
- Coursework marks go to the Student Records system; staff training completions go to the Human Resources \
system. Nothing is sold or shared for marketing.

Students under 18: the same protections apply. A parent or guardian may ask on the student's behalf \
through the Registry.

How long it is kept (proposed, to be confirmed by GSA)
- Submissions, marks and feedback: 6 years after the end of the term of the course.
- Sign-in attempts: 1 year. Notifications: 2 years.
- The audit record of changes: kept as GSA's evidence of how the system was used.
GSA disposes of records only when a second person approves.

What you can ask for
- To see and download what the LMS holds about you: open "My data".
- To have something corrected: ask from "My data". A course administrator answers within 30 days. Names, \
numbers and class lists are corrected in the Student Records or Human Resources system.
- To complain to the Data Protection Commissioner if you are not satisfied.

When this notice changes, the new version is shown to you when you next sign in."""
