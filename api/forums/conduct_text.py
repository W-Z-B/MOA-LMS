BODY = """\
Forums and messages in the GSA LMS are part of your course. Before you post or send a message, read and \
accept these rules. They apply to students and staff alike. This is a draft, to be confirmed by GSA.

Be respectful. Disagree with ideas, not with people. No insults, threats, harassment, or remarks about \
anyone's race, religion, sex, age, disability, home or campus.

Keep to the course. Post what helps others learn. No advertising, chain messages or political campaigning.

Protect people's privacy. Do not post anyone's personal details, photographs of people without their \
agreement, or private messages without the sender's agreement.

Be honest. Do not share answers to assessed work, post someone else's work as your own, or pretend to be \
someone else.

Respect other people's work. Share only material you are allowed to share, and say where it comes from.

Moderators. The teaching staff of each course and the course administrators moderate. They may hide or \
remove a post that breaks these rules, and every action they take is recorded. If you see a post that \
breaks them, report it: a moderator reviews every report.

The law. Sending threatening, abusive or indecent messages, publishing someone's private information, or \
pretending to be someone else online may be an offence under the Cybercrime Act 2018 of Guyana. GSA may \
pass such posts to the police, and may also act under its own student and staff rules.
"""
